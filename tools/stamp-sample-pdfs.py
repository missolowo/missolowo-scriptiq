#!/usr/bin/env python3
"""Give the three homepage sample PDFs a real title.

    python3 tools/stamp-sample-pdfs.py

WHY THIS FILE EXISTS

jsPDF writes no /Title into a document it makes. Nothing on screen shows
that, so it went unnoticed until the samples went on the homepage. A PDF
with no title is headed in a search result — and in an AI answer — by its
filename. "sample-script-breakdown.pdf" is a worse answer to "what does a
script breakdown look like" than the document itself is.

The documents are generated by app.html, which is LOCKED. So the titles
are stamped onto the committed copies here rather than added to the
generator. That means: IF THE SAMPLES ARE EVER REGENERATED FROM A NEW
RUN, RUN THIS AGAIN, or they go back to having no title.

It touches metadata only. Page content is not read, rewritten or
re-encoded; tools/verify-sample-pdfs.py proves that after every run.
"""
import sys
import pikepdf

FILM = 'WHEN LOVE FINDS YOU'
SITE = 'Missolowo Slate'

DOCS = {
    'docs/sample-script-breakdown.pdf': (
        'Script Breakdown',
        'A complete script breakdown: every scene with its cast, props, '
        'wardrobe, vehicles, special equipment and background, and page '
        'counts measured in eighths. Produced by Missolowo Slate from the '
        'screenplay, unedited.',
        'script breakdown, scene breakdown, eighths, production breakdown, '
        'pre-production, filmmaking, Nollywood',
    ),
    'docs/sample-shooting-schedule.pdf': (
        'Shooting Schedule',
        'A shooting schedule: the production board in the standard strip '
        'colours, the day-by-day, cast release, day out of days and '
        'department load. Produced by Missolowo Slate from the screenplay, '
        'unedited.',
        'shooting schedule, production board, stripboard, day out of days, '
        'cast release, first assistant director, Nollywood',
    ),
    'docs/sample-call-sheet.pdf': (
        'Call Sheet',
        'A call sheet for one shoot day: the scenes being shot, cast calls, '
        'locations, unit moves and tomorrow’s advance schedule. Produced '
        'by Missolowo Slate, unedited.',
        'call sheet, crew call, cast call times, unit move, advance '
        'schedule, first assistant director, Nollywood',
    ),
}


def stamp(path, kind, subject, keywords):
    title = f'{kind} — {FILM} (Sample) | {SITE}'
    with pikepdf.open(path, allow_overwriting_input=True) as pdf:
        # Writing XMP rebuilds the document info dictionary from the XMP,
        # which silently drops anything the XMP has no field for — the
        # first run of this script lost /Producer and /CreationDate that
        # way. So keep what was there and put it back afterwards.
        keep = {k: v for k, v in pdf.docinfo.items()
                if str(k) in ('/Producer', '/CreationDate', '/ModDate')}

        with pdf.open_metadata(set_pikepdf_as_editor=False) as meta:
            meta['dc:title'] = title
            meta['dc:description'] = subject
            meta['dc:creator'] = [SITE]
            meta['pdf:Keywords'] = keywords

        # The document info dictionary as well: it is what most crawlers
        # and PDF readers still look at first.
        for k, v in keep.items():
            pdf.docinfo[k] = v
        pdf.docinfo['/Title'] = title
        pdf.docinfo['/Subject'] = subject
        pdf.docinfo['/Author'] = SITE
        pdf.docinfo['/Keywords'] = keywords
        pdf.save(path)
    return kind


if __name__ == '__main__':
    for path, (kind, subject, keywords) in DOCS.items():
        try:
            stamp(path, kind, subject, keywords)
        except FileNotFoundError:
            print(f'  MISSING  {path}')
            sys.exit(1)
        print(f'  stamped  {path}  ->  {kind} — {FILM} (Sample) | {SITE}')
    print('\nNow run: python3 tools/verify-sample-pdfs.py')
